button.addEventListener("click", function () {

    // 1. Collect the user's 9 input values
    let mine = [
        input1.value,
        input2.value,
        input3.value,
        input4.value,
        input5.value,
        input6.value,
        input7.value,
        input8.value,
        input9.value
    ].map(value => value.trim() === "" ? NaN : Number(value));

    // 2. Validate inputs
    if (mine.some(value =>
        !Number.isFinite(value) ||
        value < 1 ||
        value > 10 ||
        !Number.isInteger(value)
    )) {
        pikachu.textContent =
            "Please enter all 9 values between 1 and 10.";
        return;
    }

    // 3. Calculate distance from every dataset row
    let distances = [];

    for (let i = 0; i < arjun.length; i++) {

        let distance = 0;

        for (let j = 0; j < 9; j++) {

            let datasetValue = Number(arjun[i][j + 1]);
            let difference = mine[j] - datasetValue;

            distance += difference * difference;
        }

        distances.push({
            index: i,
            distance: distance,
            classLabel: Number(arjun[i][10])
        });
    }

    // 4. Sort: nearest patients first
    distances.sort((a, b) => a.distance - b.distance);

    // 5. Select the 5 nearest patients
    let k = Math.min(5, distances.length);
    let nearest = distances.slice(0, k);

    let votes = { 0: 0, 1: 0 };

    for (let patient of nearest) {
        votes[patient.classLabel]++;
    }

    // 6. Majority voting
    let predictedClass = votes[1] > votes[0] ? 1 : 0;

    // 7. Show result on webpage
    pikachu.textContent =
        "Experimental prediction: Class " + predictedClass +
        " | Class 0 votes: " + votes[0] +
        " | Class 1 votes: " + votes[1];

    console.log("Nearest patients:", nearest);
    console.log("Votes:", votes);
    console.log("Predicted class:", predictedClass);
    // 7. Calculate voting percentages
let malignantPercent = Math.round((votes[1] / k) * 100);
let benignPercent = Math.round((votes[0] / k) * 100);

// 8. Show prediction and percentages
if (predictedClass === 1) {
    pikachu.innerHTML = `
        <h2>Prediction: Malignant-like</h2>
        <h3>Malignant vote share: ${malignantPercent}%</h3>
        <p>Benign vote share: ${benignPercent}%</p>
    `;
} else {
    pikachu.innerHTML = `
        <h2>Prediction: Benign-like</h2>
        <h3>Benign vote share: ${benignPercent}%</h3>
        <p>Malignant vote share: ${malignantPercent}%</p>
    `;
}

console.log("Votes:", votes);
console.log("Malignant vote share:", malignantPercent + "%");
console.log("Benign vote share:", benignPercent + "%");
});


